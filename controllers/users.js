const User = require("../models/User.js");
const passport = require("passport");

module.exports.renderSignup = (req,res) => {
    res.render("users/signup.ejs");
};

module.exports.signup = async (req, res, next) => {
    try {
        let { username, email, password } = req.body;
        const newUser = new User({ email, username });

        const registeredUser = await User.register(newUser, password);
        req.login(registeredUser, (err) => {
            if (err) return next(err);
            req.flash("success", "Welcome to Wanderlust!");
            res.redirect("/listings");
        });
    } catch (e) {
        req.flash("error", e.message);
        res.redirect("/signup");
    }
};

module.exports.renderLogin = (req,res) => {
    res.render("users/login.ejs");
};

module.exports.login =  (req, res, next) => {
    // save what you need BEFORE passport regenerates the session
    const pendingReview = req.session.pendingReview;
    const returnTo = req.session.returnTo || res.locals.redirectUrl || "/listings";

    passport.authenticate("local", { failureRedirect: "/login", failureFlash: true },
        async (err, user, info) => {
            if (err) return next(err);
            if (!user) {
                req.flash("error", "Incorrect username or password.");
                return res.redirect("/login");
            }

            req.logIn(user, (err) => {
                if (err) return next(err);
                // session has been regenerated by now
                // restore what you saved above
                req.flash("success", "Welcome Back!");

                if (pendingReview) {
                    return res.redirect(`/listings/${pendingReview.listingId}`);
                }

                return res.redirect(returnTo);
            });
        }
    )(req, res, next);
};

module.exports.logOut =  (req,res) => {
    req.logOut((err) => {
        if(err) return next(err);
        req.flash("success","Logged Out Successfully.");
        res.redirect("/listings");
    })
};